suppressPackageStartupMessages({library(data.table);library(jsonlite);library(digest)})
D<-'columns/001-ball-count/analysis/history_comparison_20260928_r01'
read<-function(n)fread(file.path(D,'tables',paste0(n,'.csv')))
a<-read('bcai_all_132');b<-read('bcap_all_2552_screened');cs<-read('bcap_pattern_counts_all_groups');weights<-read('annual_summary_weights')
raw<-fread('columns/001-ball-count/analysis/r_bcap_history_20260928/summary.csv')
checks<-list()
ck<-function(n,v){checks[[n]]<<-isTRUE(v);if(!isTRUE(v))stop(n)}
ck('all_12_counts_11_seasons',nrow(a)==132&&all(a[,.N,by=year]$N==12))
start<-a[count=='0-0',.(year,W0=value)];q<-merge(a,start,by='year')
ck('BCAI_ratio',max(abs(q$index-100*q$value/q$W0))<1e-9)
ck('all_report_groups_screened',nrow(b)==2552&&all(b[,.N,by=game_year]$N==232))
gate<-with(raw,n>=500&ESS0>=200&ESS1>=200&games0>=100&games1>=100&coverage>=.5&max_game_share0<=.05&max_game_share1<=.05)
ck('saved_support_gate_recomputed',identical(gate,raw$support_gate))
ck('unsupported_values_withheld',b[support_gate==FALSE,all(is.na(delta)&is.na(family95_low)&is.na(family95_high))])
ck('supported_delta_equals_Q1_minus_Q0',b[support_gate==TRUE,max(abs(delta-(Q1-Q0)))]<1e-12)
ok<-b[support_gate==TRUE];crit<-qt(1-.05/(2*ok$comparison_family),ok$games-1)
ck('BCAP_frozen_interval_formula',max(abs(ok$family95_low-(ok$delta-crit*ok$SE)),abs(ok$family95_high-(ok$delta+crit*ok$SE)))<1e-10)
ck('annual_weights_normalized',all(abs(weights[,.(e=sum(equal_year_weight),p=sum(start_PA_weight)),by=window][,e]-1)<1e-12)&&all(abs(weights[,.(p=sum(start_PA_weight)),by=window]$p-1)<1e-12))
ck('pattern_partition',all(cs$positive+cs$negative==cs$years_supported)&all(cs$clear_positive+cs$clear_negative+cs$unclear==cs$years_supported)&all(cs$years_supported+cs$unsupported==cs$years_total))
ck('counts_no_duplicate_keys',!anyDuplicated(b[,.(model,game_year,level,count,region,pitch_group)]))
h<-fread(file.path(D,'audit/source_hashes.csv'));h[,actual_sha256:=vapply(path,function(p)digest(file=p,algo='sha256',serialize=FALSE),character(1))]
ck('all_used_sources_unchanged',all(h$sha256==h$actual_sha256))
fwrite(h,file.path(D,'audit/source_hashes_after.csv'),bom=TRUE)
claims<-read('original_claim_ledger');ck('original_claim_sources_exist',all(file.exists(claims$source)))
rs<-claims[!grepl('보고서 묶음',run_id),run_id];ck('original_claim_run_ids_exist',all(dir.exists(file.path('columns/001-ball-count/analysis/runs',rs))))
code<-list.files(D,pattern='\\.(R|mjs)$',full.names=TRUE)
fwrite(data.table(path=code,sha256=vapply(code,function(p)digest(file=p,algo='sha256',serialize=FALSE),character(1))),file.path(D,'audit/code_hashes.csv'),bom=TRUE)
write_json(list(pass=all(unlist(checks)),checks=checks,source_files=nrow(h),complete_run_manifests=sum(h$role=='completed manifest'),note='Saved-output arithmetic/provenance audit only; no raw-data refit or inferential validation.'),file.path(D,'audit/numerical_verification.json'),auto_unbox=TRUE,pretty=TRUE)
print(checks)
